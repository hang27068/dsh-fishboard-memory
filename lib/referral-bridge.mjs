/**
 * 清洗一段文本，只留下「人真正说的话」。
 *
 * ⚠ 纯字符串操作，不调模型、不做推断、可审计。
 * ⚠ 宁可多剁，不可漏剁 —— 漏一个 runtime-context 就够把补充查询污染掉。
 *
 * @param {*} 文
 * @returns {string}
 */
export function 清洗文本(文) {
  let s = String(文 == null ? '' : 文)
  if (!s) return ''

  // ① 压缩摘要：从标记到结尾全丢
  const 低 = s.toLowerCase()
  let 切 = -1
  for (const m of 压缩标记) {
    const i = 低.indexOf(m)
    if (i >= 0 && (切 < 0 || i < 切)) 切 = i
  }
  if (切 >= 0) s = s.slice(0, 切)

  // ② 注入块头：从最早出现的块头到结尾全丢
  for (const h of 注入块头们) {
    const i = s.indexOf(h)
    if (i >= 0) s = s.slice(0, i)
  }

  // ③ <system-reminder>…</system-reminder>
  s = s.replace(/<system-reminder>[\s\S]*?<\/system-reminder>/gi, ' ')

  // ④ 宿主 runtime-context 行：整行丢
  if (s.includes('\n')) {
    s = s.split(/\r?\n/)
      .filter((行) => {
        const t = 行.trim()
        if (!t) return false
        return !系统块标记.some((m) => t.startsWith(m) || t.includes(m))
      })
      .join(' ')
  } else if (系统块标记.some((m) => s.includes(m))) {
    // 单行也含系统块标记 —— 整段不要（它一定不是他说的）
    s = ''
  }

  return s.replace(/\s+/g, ' ').trim()
}

